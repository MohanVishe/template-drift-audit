"""Write docs/results.md, the website's results page, from saved runs (no network).

Inputs: runs/p2-headline.json (scripts/headline.py), runs/p2-lint.json (scripts/lint_population.py),
and each run's run.json and models/*.json. Every number on the page comes from these files.

Usage: python scripts/results_page.py [--runs runs] [--out docs/results.md]
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

PLAIN = {
    "TOOL_RESULT": "tool results laid out differently or left out",
    "DEFAULT_SYSTEM": "a default instruction added or dropped",
    "TOOL_CALL": "the model's earlier tool requests written differently",
    "TOOLS_DROPPED": "the tool list not shown",
    "TOOL_SCHEMA": "tool descriptions or tool instructions worded differently",
    "TOOL_SCHEMA_NOT_JSON": "tools described in Go format instead of JSON",
    "CONTENT": "message text changed",
    "STRUCTURE": "turn layout changed",
    "THINKING": "thinking-block handling differs",
    "OTHER": "other wording differs",
}
WHERE = {
    "Ollama": "Ollama's version",
    "conversion": "the model file",
    "conversion and Ollama": "both",
    "no GGUF template": "Ollama's version (file has no template)",
}


def _yes(b: bool) -> str:
    return "yes" if b else "no"


def _table(rows: list[dict]) -> list[str]:
    out = ["| Model | Built for tools | Differs | Differs, order-only set aside | Where | What changes |",
           "|---|---|---|---|---|---|"]
    for r in rows:
        what = "; ".join(PLAIN.get(c, c) for c in r["strict_classes"]) or (
            "only the order of fields in tool descriptions" if r["material"] else "")
        out.append(f"| `{r['package']}` | {_yes(r['tool_capable'])} | {_yes(r['material'])} | "
                   f"{_yes(r['strict'])} | {WHERE.get(r['origin'], '') if r['material'] else ''} | {what} |")
    return out


def _not_compared(run_dir: Path, scored: set[str]) -> list[str]:
    meta = json.loads((run_dir / "run.json").read_text(encoding="utf-8"))
    out = [f"- `{e['package']}`: {e['reason']}" for e in meta.get("excluded", [])]
    for mp in sorted((run_dir / "models").glob("*.json")):
        m = json.loads(mp.read_text(encoding="utf-8"))
        pkg = m["target"]["package"]
        if pkg in scored:
            continue
        if m["status"] == "skipped":
            why = "Hugging Face's download service returned an error (HTTP 400) for this file name"
        elif m["selection"].get("source") == "harmony":
            why = "Ollama lays out this model's conversations with special code (\"harmony\") that this study doesn't reproduce"
        else:
            why = "the maker's template could not show any of the six tool conversations"
        out.append(f"- `{pkg}`: {why[0].upper() + why[1:]}.")
    return out


def _stale(run_dir: Path) -> list[str]:
    out = []
    for mp in sorted((run_dir / "models").glob("*.json")):
        m = json.loads(mp.read_text(encoding="utf-8"))
        cv = m.get("conversion") or {}
        if cv.get("match") == "exact" and cv.get("replaced_by"):
            nb = cv["replaced_by"]
            out.append(f"| `{m['target']['package']}` | {cv['date'][:10]} | {nb['date'][:10]} | {nb['title']} |")
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", default=str(ROOT / "runs"))
    ap.add_argument("--out", default=str(ROOT / "docs" / "results.md"))
    args = ap.parse_args()
    runs = Path(args.runs)
    head = json.loads((runs / "p2-headline.json").read_text(encoding="utf-8"))
    lint = json.loads((runs / "p2-lint.json").read_text(encoding="utf-8"))
    lib, hf = head["p2-library"], head["p2-hf"]

    def scored(h):
        return [r for r in h["packages"] if r["fixtures_compared"]]

    def line(h):
        a, t = h["summary"]["all"], h["summary"]["tool_capable"]
        return (f"| {a['material']} of {a['packages']} | {a['strict']} of {a['packages']} | "
                f"{t['material']} of {t['packages']} | {t['strict']} of {t['packages']} |")

    stale = _stale(runs / "p2-library")
    lib_models = len(list((runs / "p2-library" / "models").glob("*.json")))
    L = [
        "---",
        "layout: default",
        "title: Results",
        "description: Every model measured, what differs, and where the difference comes from.",
        "---",
        "",
        "<!-- Generated by scripts/results_page.py from runs/. Edit the script, not this file. -->",
        "",
        "# Results",
        "",
        "Snapshot of 22 October 2026, Ollama v0.40.7. For each model, the text the model would read",
        "was produced three ways (the maker's template, the copy inside the model file, and what Ollama",
        "uses) for six practice conversations that involve tools. A model \"differs\" if, in at least",
        "one of them, Ollama's text changes what the model is told compared with the maker's. Spaces,",
        "line breaks, the date and the start-of-text marker don't count. [How it works](how-it-works.html)",
        "explains the method.",
        "",
        "## Summary",
        "",
        "| | Differs | Differs, order-only set aside | Built for tools: differs | Built for tools: order-only set aside |",
        "|---|---|---|---|---|",
        "| Ollama library " + line(lib),
        "| Hugging Face " + line(hf),
        "",
        "{% include fig/stats.html %}",
        "",
        "{% include fig/grid.html %}",
        "",
        "\"Order-only\" means the only change is the order of the fields inside a tool's description,",
        "for example `required` listed before `properties`. \"Built for tools\" means the maker's own",
        "template shows the model the list of tools.",
        "",
        "## Ollama library: the 50 most popular chat models",
        "",
        *_table(scored(lib)),
        "",
        "### Not compared",
        "",
        *_not_compared(runs / "p2-library", {r["package"] for r in scored(lib)}),
        "",
        "## Hugging Face: the 30 most downloaded chat models",
        "",
        "For these, Ollama uses the template inside the file. It fills it in with a separate engine,",
        "which this study reproduces in Python. That copy is very close but not byte-for-byte Ollama.",
        "",
        *_table(scored(hf)),
        "",
        "### Not compared",
        "",
        *_not_compared(runs / "p2-hf", {r["package"] for r in scored(hf)}),
        "",
        "## Old copies inside model files",
        "",
        f"In {len(stale)} of the {lib_models} library model files, the template inside matches an",
        "older version of the maker's template. The table shows the date of that version and the",
        "maker's next change to it.",
        "",
        "| Model | File matches the maker's version of | Maker changed it on | Maker's note for that change |",
        "|---|---|---|---|",
        *stale,
        "",
        "## How often the check-up's template warning fires",
        "",
        f"The check-up's template rules were run over {lint['distinct_templates']} different templates",
        f"from {lint['packages']} models in this study (the maker's, the model file's and Ollama's). It",
        f"flagged {lint['distinct_templates_flagged']}. Read by hand, each one is a visible feature, not",
        "hidden instructions:",
        "",
    ]
    for r in lint["flagged"]:
        for layer, fl in r["flags"].items():
            words = sorted({f.split('"')[1] for f in fl if '"' in f})
            L.append(f"- `{r['package']}` ({layer.split(':')[0]}): reacts to "
                     + ", ".join(f"`{w}`" for w in words) + ".")
    L += [
        "",
        "The two models with `<|think_…|>` words let you switch their thinking mode by typing those",
        "words. `gpt-oss` uses its channel markers to separate its reasoning from its answer.",
        "",
        "## Known gaps",
        "",
        "- Mistral's own templates accept only nine-character tool request numbers. The practice",
        "  conversations use `call_1`, so those comparisons couldn't run and aren't counted.",
        "- The automatic sorter doesn't know a few model-specific markers (DeepSeek's start-of-text",
        "  marker, for example), so it labels them \"other wording\". Each was checked by hand. The",
        "  others are real wording differences. The DeepSeek marker is not, but no model's result",
        "  depends on it.",
        "- A file with no template of its own can't be checked for old copies.",
        "",
        "Raw data and the scripts that produced this page:",
        "[github.com/MohanVishe/template-drift-audit](https://github.com/MohanVishe/template-drift-audit).",
        "",
    ]
    Path(args.out).write_text("\n".join(L), encoding="utf-8", newline="\n")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
