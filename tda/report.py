"""Write a run to disk and render its report (Markdown + CSV) from the saved JSON.

  runs/<run>/run.json              tool, Ollama and fixture versions, classifier hash, sources read
  runs/<run>/models/<slug>.json    one ModelAudit per package (layers, selection, cells)
  runs/<run>/renders/<slug>/...    every rendered prompt, <layer>.<fixture>.txt
  runs/<run>/report.md, cells.csv  regenerated by `tda report` from the files above
"""

from __future__ import annotations

import csv
import json
import re
from collections import Counter
from pathlib import Path

from tda.classify import SEVERITY
from tda.fixtures import TOOL_SET

PAIR_LABEL = {"conversion": "L0→L1", "packaging": "L1→L3", "end_to_end": "L0→L3"}
_ORDER = {"n/a": -1, "none": 0, "minor": 1, "material": 2}
NOT_DRIFT = {"REFERENCE_ERROR", "BOTH_ERROR"}  # the reference side failed; nothing to compare


def slug(package: str) -> str:
    return re.sub(r"[^A-Za-z0-9._-]+", "_", package).strip("_")


def save(run_dir: Path, run_meta: dict, audits) -> None:
    run_dir = Path(run_dir)
    (run_dir / "models").mkdir(parents=True, exist_ok=True)
    for a in audits:
        s = slug(a.target.package)
        d = a.to_json()
        rdir = run_dir / "renders" / s
        rdir.mkdir(parents=True, exist_ok=True)
        for name, layer in a.layers.items():
            for fx_id, prompt in zip(run_meta["fixture_ids"], layer.prompts):
                if prompt is not None:
                    (rdir / f"{name}.{fx_id}.txt").write_text(prompt, encoding="utf-8", newline="")
            d["layers"][name].pop("prompts")  # on disk as files; JSON keeps errors and provenance
        (run_dir / "models" / f"{s}.json").write_text(json.dumps(d, indent=1, ensure_ascii=False), encoding="utf-8")
    (run_dir / "run.json").write_text(json.dumps(run_meta, indent=1), encoding="utf-8")


def load(run_dir: Path) -> tuple[dict, list[dict]]:
    run_dir = Path(run_dir)
    meta = json.loads((run_dir / "run.json").read_text(encoding="utf-8"))
    models = [json.loads(p.read_text(encoding="utf-8")) for p in sorted((run_dir / "models").glob("*.json"))]
    return meta, models


def _worst(cells, pair, fixtures=None) -> str:
    sev = [c["severity"] for c in cells if c["pair"] == pair and (fixtures is None or c["fixture"] in fixtures)]
    return max(sev, key=_ORDER.__getitem__, default="—")


def _classes(cells, pair, fixtures=None) -> list[str]:
    cs = {k for c in cells if c["pair"] == pair and (fixtures is None or c["fixture"] in fixtures)
          for k in c["classes"] if k != "IDENTICAL"}
    return sorted(cs)


def _has_pair(m, pair) -> bool:
    return any(c["pair"] == pair for c in m["cells"])


def summary(models: list[dict]) -> dict:
    """The headline count and its breakdown, over packages where L0 and L3 were both rendered."""
    scored = [m for m in models if _has_pair(m, "end_to_end")]
    hit = [m for m in scored if _worst(m["cells"], "end_to_end", TOOL_SET) == "material"]
    origin = Counter()
    for m in hit:
        conv = _worst(m["cells"], "conversion", TOOL_SET) == "material"
        pack = _worst(m["cells"], "packaging", TOOL_SET) == "material"
        origin["no GGUF template to compare" if "L1" not in m["layers"]
               else "conversion and packaging" if conv and pack else "conversion only" if conv
               else "packaging only" if pack else "neither alone"] += 1
    cls = Counter(k for m in hit for k in _classes(m["cells"], "end_to_end", TOOL_SET)
                  if k not in NOT_DRIFT and SEVERITY.get(k, "material") == "material")
    approx = [m["target"]["package"] for m in scored if not all(L["exact"] for L in m["layers"].values())]
    known = sorted({k for m in hit for c in m["cells"] for k in c.get("known_issues", [])})
    return {"scored": len(scored), "material_tool_drift": len(hit), "origin": dict(origin),
            "classes": dict(cls.most_common()), "approximate": approx, "known_issues": known,
            "not_scored": [(m["target"]["package"], m["status"], m["reason"]) for m in models if m not in scored]}


def markdown(meta: dict, models: list[dict]) -> str:
    s = summary(models)
    tool = ", ".join(sorted(TOOL_SET))
    lines = [
        f"# Template drift report — {meta['run_id']}",
        "",
        f"Ollama {meta['ollama_version']} (Go helper) · tool {meta['tool_version']} · fixtures v{meta['fixture_hash']}"
        f" · classifier {meta['classifier_sha256'][:12]} · {meta['date']}",
        "",
        "## Summary",
        "",
        f"**{s['material_tool_drift']} of {s['scored']}** audited packages give the model a prompt that differs "
        f"materially from the author's template (L0→L3) on at least one tool-calling fixture ({tool}).",
        "",
    ]
    if s["origin"]:
        lines += ["Where the difference first appears, among those packages:", ""]
        lines += [f"- {k}: {v}" for k, v in sorted(s["origin"].items())] + [""]
    if s["classes"]:
        lines += ["| Class (L0→L3, tool fixtures) | Packages |", "|---|---|"]
        lines += [f"| `{k}` | {v} |" for k, v in s["classes"].items()] + [""]
    if s["known_issues"]:
        lines += ["Already reported upstream: " + ", ".join(s["known_issues"]) + ". Findings matching these are "
                  "not new.", ""]
    if s["approximate"]:
        lines += ["Rendered on an approximate path (llama-server Jinja emulated in Python, not validated live): "
                  + ", ".join(s["approximate"]), ""]

    lines += ["## Packages", "",
              "| Package | Source | L0→L1 | L1→L3 | L0→L3 | L0→L3 classes (tool fixtures) | Known |",
              "|---|---|---|---|---|---|---|"]
    for m in models:
        c = m["cells"]
        known = sorted({k for x in c for k in x.get("known_issues", [])})
        lines.append(f"| `{m['target']['package']}` | {m['selection'].get('source', '—')} | "
                     f"{_worst(c, 'conversion')} | {_worst(c, 'packaging')} | {_worst(c, 'end_to_end')} | "
                     f"{', '.join(_classes(c, 'end_to_end', TOOL_SET)) or '—'} | {', '.join(known) or '—'} |")
    lines.append("")

    for m in models:
        lines += [f"### `{m['target']['package']}`", ""]
        t = m["target"]
        if t.get("upstream_repo"):
            lines.append(f"- L0: {m['layers'].get('L0', {}).get('source', t['upstream_repo'])}"
                         + (f" — {t['reason']}" if t.get("reason") else "")
                         + (f" (confidence {t['confidence']})" if t.get("confidence") else ""))
        conv = m.get("conversion") or {}
        if conv.get("match") in ("exact", "whitespace"):
            how = "is" if conv["match"] == "exact" else "is, up to whitespace,"
            line = (f"- GGUF template {how} an older revision of the author's template: newest match "
                    f"{conv['sha'][:12]} ({conv['date'][:10]})")
            if conv.get("replaced_by"):
                r = conv["replaced_by"]
                line += f"; changed upstream in {r['sha'][:12]} ({r['date'][:10]}, \"{r['title']}\")"
            lines.append(line)
        elif conv.get("match") == "none":
            lines.append(f"- GGUF template matches none of the {conv['commits_checked']} upstream revisions checked")
        elif conv.get("match") == "unknown":
            lines.append(f"- Upstream revision of the GGUF template not checked: {conv['error'][:120]}")
        sel = m["selection"]
        if sel:
            lines.append(f"- Ollama selects `{sel['source']}`" + (" (SYSTEM layer present)" if sel.get("system_layer") else ""))
        if m["status"] != "audited":
            lines.append(f"- Status: {m['status']} — {m['reason']}")
        errs = {f"{name}.{fx}": e for name, L in m["layers"].items()
                for fx, e in zip(meta["fixture_ids"], L["errors"]) if e}
        if errs:
            lines.append("- Render errors: " + "; ".join(f"{k}: {v[:80]}" for k, v in errs.items()))
        pairs = [p for p in PAIR_LABEL if _has_pair(m, p)]
        if pairs:
            lines += ["", "| Fixture | " + " | ".join(PAIR_LABEL[p] for p in pairs) + " |",
                      "|---|" + "---|" * len(pairs)]
            for fx in meta["fixture_ids"]:
                row = []
                for p in pairs:
                    cell = next((x for x in m["cells"] if x["pair"] == p and x["fixture"] == fx), None)
                    row.append(", ".join(cell["classes"]) if cell else "—")
                lines.append(f"| {fx}{' (tools)' if fx in TOOL_SET else ''} | " + " | ".join(row) + " |")
        lines.append("")

    if s["not_scored"]:
        lines += ["## Not in the headline count", ""]
        lines += [f"- `{p}`: {st} — {r}" for p, st, r in s["not_scored"]] + [""]
    if meta.get("excluded"):
        lines += ["## Excluded by the mapping", ""]
        lines += [f"- `{e['package']}`: {e['reason']}" for e in meta["excluded"]] + [""]
    lines += ["## Method notes", "",
              "- Severity: `none` (whitespace, BOS, date), `minor` (same JSON, different spacing or escapes), "
              "`material` (everything else). Classes are defined in `labels/GUIDE.md`.",
              "- L0 and L1 are rendered with the L0 special tokens, so L0→L1 compares template text only.",
              "- A fixture the reference side cannot render is marked `REFERENCE_ERROR` and is not counted as drift.",
              f"- Sources read: {len(meta.get('sources', []))} URLs (listed in run.json); "
              f"network requests this run: {meta.get('network_requests', 0)}.", ""]
    return "\n".join(lines)


def write_csv(path: Path, models: list[dict]) -> None:
    with open(path, "w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(["package", "kind", "selected_source", "fixture", "tool_fixture", "pair", "severity", "classes",
                    "known_issues"])
        for m in models:
            for c in m["cells"]:
                w.writerow([m["target"]["package"], "hf" if m["target"]["package"].startswith("hf.co/") else "library",
                            m["selection"].get("source", ""), c["fixture"], c["fixture"] in TOOL_SET, c["pair"],
                            c["severity"], ";".join(c["classes"]), ";".join(c.get("known_issues", []))])


def build(run_dir: Path) -> Path:
    meta, models = load(run_dir)
    out = Path(run_dir) / "report.md"
    out.write_text(markdown(meta, models), encoding="utf-8")
    write_csv(Path(run_dir) / "cells.csv", models)
    return out
